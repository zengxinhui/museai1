#!/usr/bin/env python3
"""Build src/nihongo/furigana.cljs: a segment -> reading dictionary.

Why this exists: Hanabira grammar examples (and ~27% of OpenJLPT
vocabulary examples) carry no furigana field, so Pick of the Day
(and some Learn examples) showed plain Japanese even with the
furigana toggle on. Today's pick on 2026-11-04 was exactly such a
grammar sentence.

Why segments, not vocabulary readings: a word->reading map gives
wrong readings for polysemous and compound words (e.g. 上手 as
うわて instead of じょうず, 日本人 split as 日本+人). Instead, this
script extracts the actual {segment|reading} pairs from every
OpenJLPT example sentence that has a furigana field (10,517
sentences) and keeps, for each kanji-containing segment, its most
frequent reading in real sentences. That gives, for example,
私 -> わたし (904 uses, vs わたくし 1), 上手 -> じょうず,
日本語 -> にほんご, 日本人 -> にほんじん.

Measured on the 1,656 Hanabira grammar sentences (which have no
source furigana at all): 99.2% of kanji characters are covered by
this dictionary, and 95% of sentences are fully covered. It is
still generated furigana, not source furigana: compounds the
dictionary has never seen as a whole segment can still be split
into parts with a reading that fits another context (e.g. 支 in
差し支え). The app marks generated furigana as generated in the
Pick of the Day view.

Output: (ns nihongo.furigana) with (def segments {segment reading}).
Run: python3 scripts/build_furigana.py
"""
import json, pathlib, re
from collections import defaultdict, Counter

ROOT = pathlib.Path(__file__).resolve().parent.parent
OPEN = ROOT / "data-raw" / "openjlpt" / "data" / "json"

def is_kanji(c):
    return 0x4E00 <= ord(c) <= 0x9FFF

def main():
    counts = defaultdict(Counter)
    total = 0
    for lvl in ["n5", "n4", "n3", "n2", "n1"]:
        for v in json.load(open(OPEN / "vocab" / f"{lvl}.json")):
            for e in v.get("examples", []):
                f = e.get("furigana") or ""
                if f:
                    total += 1
                for seg, reading in re.findall(r"\{([^|]+)\|([^}]+)\}", f):
                    if any(is_kanji(c) for c in seg):
                        counts[seg][reading] += 1
    segments = {seg: c.most_common(1)[0][0] for seg, c in counts.items()}
    print(f"sentences with furigana: {total}")
    print(f"segments: {len(segments)}")
    out = ["(ns nihongo.furigana)", "",
           ";; Generated by scripts/build_furigana.py -- do not edit by hand.",
           ";; Segment -> most frequent reading, from OpenJLPT example furigana.",
           ";; See scripts/build_furigana.py for method and limits.",
           "(def segments {"]
    for seg in sorted(segments):
        out.append(f"  {json.dumps(seg, ensure_ascii=False)} {json.dumps(segments[seg], ensure_ascii=False)}")
    out.append("})")
    dest = ROOT / "src" / "nihongo" / "furigana.cljs"
    dest.write_text("\n".join(out) + "\n", encoding="utf-8")
    print("wrote", dest, dest.stat().st_size, "bytes")

if __name__ == "__main__":
    main()
